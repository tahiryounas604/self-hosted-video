// Backend tests for self-hosted-video v0.1.
// Real end-to-end: boots the real HTTP server, uploads a real ffmpeg-generated
// sample video, waits for the real ffmpeg transcode, and checks real HLS output.
// Run: `npm test` (node --test).
import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createApp } from '../src/server.js';
import { runCommand } from '../src/transcode.js';

const TOKEN = 'test-token-12345';
const WRONG_TOKEN = 'wrong-token';

let app;
let baseUrl;
let tmpDir;
let samplePath;

function authHeaders(token = TOKEN) {
  return { Authorization: `Bearer ${token}` };
}

async function waitForStatus(id, wanted, timeoutMs = 60000) {
  const deadline = Date.now() + timeoutMs;
  let last;
  while (Date.now() < deadline) {
    const res = await fetch(`${baseUrl}/api/videos/${id}`, { headers: authHeaders() });
    last = await res.json();
    if (last.status === wanted) return last;
    if (last.status === 'failed') throw new Error(`transcode failed: ${last.error}`);
    await new Promise((r) => setTimeout(r, 500));
  }
  throw new Error(`timed out waiting for status=${wanted}; last=${JSON.stringify(last)}`);
}

async function uploadSample(title = 'Test video') {
  const buf = await fs.readFile(samplePath);
  const form = new FormData();
  form.append('title', title);
  form.append('video', new Blob([buf], { type: 'video/mp4' }), 'sample.mp4');
  const res = await fetch(`${baseUrl}/api/videos`, { method: 'POST', headers: authHeaders(), body: form });
  return res;
}

before(async () => {
  tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), 'shv-test-'));
  samplePath = path.join(tmpDir, 'sample.mp4');
  // Tiny real video: 2s, 1280x720, with audio — generated by ffmpeg.
  await runCommand('ffmpeg', [
    '-y',
    '-f', 'lavfi', '-i', 'testsrc=duration=2:size=1280x720:rate=30',
    '-f', 'lavfi', '-i', 'sine=frequency=440:duration=2',
    '-c:v', 'libx264', '-pix_fmt', 'yuv420p',
    '-c:a', 'aac', '-shortest',
    samplePath,
  ]);
  const dataDir = path.join(tmpDir, 'data');
  app = createApp({ dataDir, token: TOKEN });
  const port = await app.start(0);
  baseUrl = `http://127.0.0.1:${port}`;
});

after(async () => {
  if (app) await app.close();
  if (tmpDir) await fs.rm(tmpDir, { recursive: true, force: true });
});

test('health endpoint is public and reports ok', async () => {
  const res = await fetch(`${baseUrl}/api/health`);
  assert.equal(res.status, 200);
  const body = await res.json();
  assert.equal(body.ok, true);
  assert.equal(body.service, 'self-hosted-video');
});

test('auth enforcement: no token -> 401 on list, upload, status, delete, HLS', async () => {
  const list = await fetch(`${baseUrl}/api/videos`);
  assert.equal(list.status, 401);

  const form = new FormData();
  form.append('video', new Blob(['x'], { type: 'video/mp4' }), 'x.mp4');
  const upload = await fetch(`${baseUrl}/api/videos`, { method: 'POST', body: form });
  assert.equal(upload.status, 401);

  const status = await fetch(`${baseUrl}/api/videos/some-id`);
  assert.equal(status.status, 401);

  const del = await fetch(`${baseUrl}/api/videos/some-id`, { method: 'DELETE' });
  assert.equal(del.status, 401);

  const hls = await fetch(`${baseUrl}/hls/some-id/master.m3u8`);
  assert.equal(hls.status, 401);
});

test('auth enforcement: wrong token -> 401', async () => {
  const res = await fetch(`${baseUrl}/api/videos`, { headers: authHeaders(WRONG_TOKEN) });
  assert.equal(res.status, 401);
});

test('auth enforcement: ?token= query param is accepted for HLS', async () => {
  // Upload first so a real HLS URL exists.
  const up = await uploadSample('Query token video');
  assert.equal(up.status, 201);
  const video = await up.json();
  const ready = await waitForStatus(video.id, 'ready');
  assert.equal(ready.status, 'ready');
  const res = await fetch(`${baseUrl}/hls/${video.id}/master.m3u8?token=${TOKEN}`);
  assert.equal(res.status, 200);
  const bad = await fetch(`${baseUrl}/hls/${video.id}/master.m3u8?token=${WRONG_TOKEN}`);
  assert.equal(bad.status, 401);
});

test('upload flow: multipart upload returns 201 with metadata', async () => {
  const res = await uploadSample('Upload flow video');
  assert.equal(res.status, 201);
  const video = await res.json();
  assert.ok(video.id);
  assert.equal(video.title, 'Upload flow video');
  assert.equal(video.original_filename, 'sample.mp4');
  assert.ok(['uploaded', 'processing'].includes(video.status));
  // Status endpoint reflects the same video.
  const got = await fetch(`${baseUrl}/api/videos/${video.id}`, { headers: authHeaders() });
  assert.equal(got.status, 200);
  assert.equal((await got.json()).id, video.id);
});

test('upload validation: missing file -> 400; unknown id -> 404', async () => {
  const form = new FormData();
  form.append('title', 'no file');
  const res = await fetch(`${baseUrl}/api/videos`, { method: 'POST', headers: authHeaders(), body: form });
  assert.equal(res.status, 400);
  assert.match((await res.json()).error, /video file/i);

  const missing = await fetch(`${baseUrl}/api/videos/does-not-exist`, { headers: authHeaders() });
  assert.equal(missing.status, 404);

  const delMissing = await fetch(`${baseUrl}/api/videos/does-not-exist`, { method: 'DELETE', headers: authHeaders() });
  assert.equal(delMissing.status, 404);
});

test('transcode: sample video reaches ready with real duration', async () => {
  const res = await uploadSample('Transcode video');
  const video = await res.json();
  const ready = await waitForStatus(video.id, 'ready');
  assert.equal(ready.status, 'ready');
  assert.ok(ready.duration_seconds >= 1.9 && ready.duration_seconds <= 2.1,
    `expected duration ~2s, got ${ready.duration_seconds}`);
  assert.equal(ready.master_playlist_url, `/hls/${video.id}/master.m3u8`);
  assert.equal(ready.error, null);
});

test('HLS playlist correctness: master lists both renditions, variants list segments, segments exist', async () => {
  const res = await uploadSample('HLS correctness video');
  const video = await res.json();
  await waitForStatus(video.id, 'ready');

  const masterRes = await fetch(`${baseUrl}/hls/${video.id}/master.m3u8`, { headers: authHeaders() });
  assert.equal(masterRes.status, 200);
  assert.match(masterRes.headers.get('content-type'), /mpegurl/);
  const master = await masterRes.text();
  assert.match(master, /#EXTM3U/);
  assert.match(master, /720p\/playlist\.m3u8/);
  assert.match(master, /480p\/playlist\.m3u8/);
  assert.match(master, /BANDWIDTH=\d+/);
  assert.match(master, /RESOLUTION=1280x720/);
  assert.match(master, /RESOLUTION=854x480/);

  for (const rendition of ['720p', '480p']) {
    const plRes = await fetch(`${baseUrl}/hls/${video.id}/${rendition}/playlist.m3u8`, { headers: authHeaders() });
    assert.equal(plRes.status, 200, `${rendition} playlist`);
    const playlist = await plRes.text();
    assert.match(playlist, /#EXT-X-ENDLIST/, `${rendition} must be VOD (ENDLIST)`);
    const segments = [...playlist.matchAll(/^(seg\d+\.ts)$/gm)].map((m) => m[1]);
    assert.ok(segments.length >= 1, `${rendition} must list at least one segment`);
    for (const seg of segments) {
      const segRes = await fetch(`${baseUrl}/hls/${video.id}/${rendition}/${seg}`, { headers: authHeaders() });
      assert.equal(segRes.status, 200, `${rendition}/${seg}`);
      assert.match(segRes.headers.get('content-type'), /MP2T/);
      const bytes = Buffer.from(await segRes.arrayBuffer());
      assert.ok(bytes.length > 0, `${rendition}/${seg} must be non-empty`);
    }
  }
});

test('HLS security: path traversal is rejected', async () => {
  const res = await fetch(`${baseUrl}/hls/..%2F..%2Fetc/passwd`, { headers: authHeaders() });
  assert.ok([400, 404].includes(res.status), `expected 400/404, got ${res.status}`);
});

test('list + delete: video appears in list, delete removes it and its files', async () => {
  const res = await uploadSample('Delete me video');
  const video = await res.json();
  await waitForStatus(video.id, 'ready');

  const listRes = await fetch(`${baseUrl}/api/videos`, { headers: authHeaders() });
  assert.equal(listRes.status, 200);
  const list = await listRes.json();
  assert.ok(Array.isArray(list));
  assert.ok(list.some((v) => v.id === video.id), 'uploaded video must appear in list');

  const del = await fetch(`${baseUrl}/api/videos/${video.id}`, { method: 'DELETE', headers: authHeaders() });
  assert.equal(del.status, 204);

  const gone = await fetch(`${baseUrl}/api/videos/${video.id}`, { headers: authHeaders() });
  assert.equal(gone.status, 404);

  const hlsGone = await fetch(`${baseUrl}/hls/${video.id}/master.m3u8`, { headers: authHeaders() });
  assert.equal(hlsGone.status, 404);

  const listAfter = await (await fetch(`${baseUrl}/api/videos`, { headers: authHeaders() })).json();
  assert.ok(!listAfter.some((v) => v.id === video.id), 'deleted video must leave the list');
});

test('ffprobe rejects a non-video file: status becomes failed', async () => {
  const form = new FormData();
  form.append('title', 'Not a video');
  form.append('video', new Blob(['this is not a video at all'], { type: 'video/mp4' }), 'fake.mp4');
  const res = await fetch(`${baseUrl}/api/videos`, { method: 'POST', headers: authHeaders(), body: form });
  assert.equal(res.status, 201);
  const video = await res.json();
  const deadline = Date.now() + 30000;
  let last;
  while (Date.now() < deadline) {
    last = await (await fetch(`${baseUrl}/api/videos/${video.id}`, { headers: authHeaders() })).json();
    if (last.status === 'failed') break;
    await new Promise((r) => setTimeout(r, 500));
  }
  assert.equal(last.status, 'failed');
  assert.ok(last.error, 'failed video must carry an error message');
});
